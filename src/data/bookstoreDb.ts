export function findEmotion(name: string): EmotionCategory | undefined {
  return EMOTION_DATABASE.find((e) => e.name === name);
}

export function localGuessEmotion(text: string): EmotionCategory {
  const clean = text.replace(/\s+/g, "");
  let best: EmotionCategory | null = null;
  let bestScore = 0;

  for (const cat of EMOTION_DATABASE) {
    let score = 0;
    for (const pattern of cat.keywords) {
      try {
        const regex = new RegExp(pattern);
        const match = regex.exec(clean);
        if (match) {
          if (cat.isPositive && /^(않|없|못)/.test(clean.slice(match.index + match[0].length))) {
            continue;
          }
          score++;
        }
      } catch {
        // ignore regex error
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = cat;
    }
  }

  return best || findEmotion("혼란") || EMOTION_DATABASE[0];
}

export function buildEmotionCatalogString(): string {
  return EMOTION_DATABASE.map(
    (e) => `${e.name}: ${e.books.map((bk) => bk.title).join(" / ")}`
  ).join("\n");
}
